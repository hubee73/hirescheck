#!/usr/bin/env bash
# Install hirescheck for the current user.
#   virtualenv           : ${XDG_DATA_HOME:-~/.local/share}/hirescheck/.venv (the package is pip-installed into it)
#   launcher             : ~/.local/bin/hirescheck
# Usage: ./install.sh [--no-plot] [--uninstall]
# Re-running updates the program and reuses a working virtualenv.
# Written for bash 3.2 (macOS default) and newer.
set -euo pipefail

NAME=hirescheck
SRC_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SHARE_DIR="${XDG_DATA_HOME:-${HOME}/.local/share}/${NAME}"
VENV="${SHARE_DIR}/.venv"
BIN_DIR="${HOME}/.local/bin"
LAUNCHER="${BIN_DIR}/${NAME}"
MARKER="# ${NAME} launcher (generated by install.sh)"
WITH_PLOT=1

info() { printf '\033[1;32m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m警告：\033[0m%s\n' "$*" >&2; }
die() { printf '\033[1;31m错误：\033[0m%s\n' "$*" >&2; exit 1; }

usage() {
    cat <<EOF
用法：./install.sh [选项]

  --no-plot     不安装 matplotlib（不生成 spectrum.png，其余报告照常）
  --uninstall   删除 ${SHARE_DIR} 和 ${LAUNCHER}
  -h, --help    显示本帮助

可用环境变量 PYTHON 指定 Python 解释器，例如：PYTHON=python3.12 ./install.sh
EOF
}

# Install commands for the package manager this system appears to use.
hint() {
    local pkg="$1"
    case "$(uname -s)" in
        Darwin) echo "brew install ${pkg}" ;;
        Linux)
            if command -v apt-get >/dev/null 2>&1; then echo "sudo apt install $2"
            elif command -v dnf >/dev/null 2>&1; then echo "sudo dnf install $3"
            elif command -v pacman >/dev/null 2>&1; then echo "sudo pacman -S $4"
            else echo "用系统的包管理器安装 ${pkg}"; fi ;;
        *) echo "安装 ${pkg}" ;;
    esac
}

is_ours() { [ -f "$1" ] && grep -qxF "${MARKER}" "$1"; }

uninstall() {
    if [ -e "${LAUNCHER}" ]; then
        is_ours "${LAUNCHER}" || die "${LAUNCHER} 不是本脚本生成的，未删除。"
        rm -f "${LAUNCHER}" && info "已删除 ${LAUNCHER}"
    fi
    if [ -d "${SHARE_DIR}" ]; then
        # .installed-by-install.sh marks our folder; hirescheck.py marks installs from 1.4.0 and earlier.
        [ -f "${SHARE_DIR}/.installed-by-install.sh" ] || [ -f "${SHARE_DIR}/${NAME}.py" ] \
            || die "${SHARE_DIR} 不像是本脚本安装的目录，未删除。"
        rm -rf "${SHARE_DIR}" && info "已删除 ${SHARE_DIR}"
    fi
    if [ -d "${XDG_CONFIG_HOME:-${HOME}/.config}/${NAME}/chains" ]; then
        info "保留了自己学习的加工链指纹：${XDG_CONFIG_HOME:-${HOME}/.config}/${NAME}/chains"
    fi
    info "卸载完成。"
}

while [ $# -gt 0 ]; do
    case "$1" in
        --no-plot) WITH_PLOT=0 ;;
        --uninstall) uninstall; exit 0 ;;
        -h|--help) usage; exit 0 ;;
        *) usage >&2; die "未知选项：$1" ;;
    esac
    shift
done

for f in pyproject.toml "${NAME}/__init__.py"; do
    [ -f "${SRC_DIR}/${f}" ] || die "找不到 ${SRC_DIR}/${f}；请在项目目录里运行 install.sh。"
done
if [ -e "${LAUNCHER}" ] && ! is_ours "${LAUNCHER}"; then
    die "${LAUNCHER} 已存在且不是本脚本生成的，不会覆盖。请先移走它。"
fi

info "检查依赖"

# Python 3.10+ with a working venv/ensurepip (Debian splits these into python3-venv).
python_ok() { "$1" -c 'import sys, venv, ensurepip; sys.exit(sys.version_info < (3, 10))' >/dev/null 2>&1; }
PY=""
for candidate in ${PYTHON:-} python3.14 python3.13 python3.12 python3.11 python3.10 python3; do
    if command -v "${candidate}" >/dev/null 2>&1 && python_ok "${candidate}"; then
        PY="$(command -v "${candidate}")"
        break
    fi
done
if [ -z "${PY}" ]; then
    if command -v python3 >/dev/null 2>&1 && python3 -c 'import sys; sys.exit(sys.version_info < (3, 10))' 2>/dev/null; then
        die "python3 缺少 venv/ensurepip 模块。请运行：$(hint python3 python3-venv python3 python)"
    fi
    die "需要 Python 3.10 或更新版本。请运行：$(hint python@3.12 python3 python3 python)，或用 PYTHON=/路径/python3 指定。"
fi
echo "    Python：${PY}（$("${PY}" -c 'import platform; print(platform.python_version())')）"

for tool in ffmpeg ffprobe; do
    command -v "${tool}" >/dev/null 2>&1 || die "找不到 ${tool}。请安装 FFmpeg：$(hint ffmpeg ffmpeg ffmpeg ffmpeg)"
done
echo "    FFmpeg：$(command -v ffmpeg)（$(ffmpeg -hide_banner -version | head -n 1 | cut -d' ' -f3)）"
decoders="$(ffmpeg -hide_banner -decoders 2>/dev/null)"
echo "${decoders}" | grep -qw flac || die "这个 FFmpeg 不支持 FLAC 解码，请换一个完整版本的 FFmpeg。"
if ! echo "${decoders}" | grep -qw dsd_lsbf; then
    warn "这个 FFmpeg 不支持 DSD 解码，将无法检查 DSF/DFF 文件；PCM 检查不受影响。"
fi

info "安装到 ${SHARE_DIR}"
mkdir -p "${SHARE_DIR}" "${BIN_DIR}"
# Files copied there by 1.4.0 and earlier; the package now lives inside the virtualenv.
rm -rf "${SHARE_DIR}/${NAME}.py" "${SHARE_DIR}/chains" "${SHARE_DIR}/requirements.txt" "${SHARE_DIR}/requirements-noplot.txt"
[ -f "${SRC_DIR}/README.md" ] && install -m 644 "${SRC_DIR}/README.md" "${SHARE_DIR}/"
[ -f "${SRC_DIR}/README.en.md" ] && install -m 644 "${SRC_DIR}/README.en.md" "${SHARE_DIR}/"
touch "${SHARE_DIR}/.installed-by-install.sh"

# Reuse the virtualenv only if its interpreter still runs and is new enough;
# a Python upgrade (e.g. via Homebrew) can leave it pointing at a removed binary.
# An explicit PYTHON always rebuilds it with that interpreter.
if [ -z "${PYTHON:-}" ] && [ -x "${VENV}/bin/python" ] \
    && "${VENV}/bin/python" -c 'import sys; sys.exit(sys.version_info < (3, 10))' >/dev/null 2>&1; then
    echo "    复用已有虚拟环境"
else
    rm -rf "${VENV}"
    "${PY}" -m venv "${VENV}" || die "创建虚拟环境失败。"
fi

if [ "${WITH_PLOT}" = 1 ]; then
    target="${SRC_DIR}[plot]"
    modules="numpy, scipy, matplotlib"
else
    target="${SRC_DIR}"
    modules="numpy, scipy"
    "${VENV}/bin/python" -m pip uninstall --disable-pip-version-check --quiet -y matplotlib >/dev/null 2>&1 || true
fi
info "安装 hirescheck 及 Python 依赖（${modules}）"
"${VENV}/bin/python" -m pip install --disable-pip-version-check --quiet --upgrade "${target}" \
    || die "pip 安装失败，请检查网络或 pip 配置后重试。"
"${VENV}/bin/python" -c "import ${modules}, ${NAME}" || die "安装后仍无法导入：${modules}, ${NAME}"

info "生成启动器 ${LAUNCHER}"
{
    echo '#!/usr/bin/env bash'
    echo "${MARKER}"
    printf 'exec %q -I -m %q "$@"\n' "${VENV}/bin/python" "${NAME}"
} > "${LAUNCHER}"
chmod 755 "${LAUNCHER}"

"${LAUNCHER}" --version >/dev/null || die "启动器自检失败：${LAUNCHER} --version"
info "安装完成：$("${LAUNCHER}" --version)"

case ":${PATH}:" in
    *":${BIN_DIR}:"*) echo "    现在可以运行：${NAME} \"/路径/歌曲.flac\"" ;;
    *)
        case "${SHELL##*/}" in
            zsh) rc="~/.zshrc" ;;
            bash) rc="~/.bashrc（macOS 上为 ~/.bash_profile）" ;;
            *) rc="你的 shell 配置文件" ;;
        esac
        warn "${BIN_DIR} 不在 PATH 中。请把下面这行加到 ${rc}，然后重新打开终端："
        echo "    export PATH=\"\$HOME/.local/bin:\$PATH\""
        echo "    在此之前可以直接运行：${LAUNCHER} \"/路径/歌曲.flac\"" ;;
esac
